function initLanguageGate() {
  if (!elements.languageGate) return;

  // Delegate the choice to the gate itself so it survives any later DOM refresh.
  elements.languageGate.addEventListener("click", (event) => {
    const button = event.target.closest("[data-language-choice]");
    if (!button || !elements.languageGate.contains(button)) return;

    event.preventDefault();
    applyLanguagePreference(button.dataset.languageChoice || "ru");
    elements.languageGate.classList.remove("is-visible");
    document.body.classList.remove("language-gate-open");
    window.setTimeout(() => {
      elements.languageGate.hidden = true;
    }, 260);
  });

  const savedLanguage = localStorage.getItem("lr-language");
  applyLanguagePreference(savedLanguage || "ru", { persist: false });

  if (savedLanguage) return;

  elements.languageGate.hidden = false;
  document.body.classList.add("language-gate-open");
  requestAnimationFrame(() => elements.languageGate.classList.add("is-visible"));
}

function applyLanguagePreference(language, { persist = true } = {}) {
  const safeLanguage = language === "ky" ? "ky" : "ru";
  document.documentElement.lang = safeLanguage;
  document.body.dataset.language = safeLanguage;
  if (persist) localStorage.setItem("lr-language", safeLanguage);
  if (elements.whatsappHeader) {
    elements.whatsappHeader.href = whatsAppLink(safeLanguage === "ky"
      ? "Саламатсызбы! Линия Роста сайты боюнча маалымат алгым келет."
      : "Здравствуйте! Пишу с сайта Линия Роста.");
  }
  applyLanguageToPage();
}

function currentLanguage() {
  return document.body?.dataset.language === "ky" ? "ky" : "ru";
}

function localizedInterfaceText(value) {
  const original = String(value ?? "");
  const normalized = original.trim();
  if (!normalized) return original;

  let translated = normalized;
  if (currentLanguage() === "ky") {
    translated = interfaceTranslations.get(normalized) || normalized;
    const available = /^(\d+) позиций доступно$/.exec(normalized);
    if (available) translated = `${available[1]} позиция жеткиликтүү`;
    const points = /^(\d+) точки$/.exec(normalized);
    if (points) translated = `${points[1]} чекит`;
    const holes = /^(\d+) отверстий$/.exec(normalized);
    if (holes) translated = `${holes[1]} тешик`;
    const order = /^Номер заказа: (.+)\.$/.exec(normalized);
    if (order) translated = `Буйрутма номери: ${order[1]}.`;
    const perimeter = /^Контур: (.+)$/.exec(normalized);
    if (perimeter) translated = `Контур: ${perimeter[1]}`;
    const area = /^Площадь: (.+)$/.exec(normalized);
    if (area) translated = `Аянты: ${area[1]}`;
    const sketchTitle = /^Полотно (\d+)$/.exec(normalized);
    if (sketchTitle) translated = `Полотно ${sketchTitle[1]}`;
    const tap = /^Тапните: (.+)$/.exec(normalized);
    if (tap) {
      const holeLabels = { труба: "түтүк", люстра: "люстра", точка: "чекит" };
      translated = `Басыңыз: ${holeLabels[tap[1]] || tap[1]}`;
    }
    const missingDimensions = /^Введите точные размеры сторон: (.+)\.$/.exec(normalized);
    if (missingDimensions) translated = `Тараптардын так өлчөмдөрүн киргизиңиз: ${missingDimensions[1]}.`;
    const addedToCart = /^Добавлено в корзину: (.+)$/.exec(normalized);
    if (addedToCart) translated = `Себетке кошулду: ${addedToCart[1]}`;
    const selectedCanvas = /^Выберите место на полотне: (.+)$/.exec(normalized);
    if (selectedCanvas) translated = `Полотнонун жайгашкан жерин тандаңыз: ${selectedCanvas[1]}`;
    const aiDraft = /^AI-черновик готов\.(.*)$/.exec(normalized);
    if (aiDraft) translated = `AI караламасы даяр болду.${aiDraft[1]}`;
    const revision = /^Редакция: (.+)$/.exec(normalized);
    if (revision) translated = `Редакциясы: ${revision[1]}`;
  } else {
    translated = reverseInterfaceTranslations.get(normalized) || normalized;
  }

  if (translated === normalized) return original;
  const leading = original.match(/^\s*/)?.[0] || "";
  const trailing = original.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

function applyLanguageToPage() {
  if (!document.body) return;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("script,style")) continue;
    const translated = localizedInterfaceText(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
  }

  document.body.querySelectorAll("[placeholder], [aria-label], [title], [alt]").forEach((node) => {
    ["placeholder", "aria-label", "title", "alt"].forEach((attribute) => {
      const value = node.getAttribute(attribute);
      if (!value) return;
      const translated = localizedInterfaceText(value);
      if (translated !== value) node.setAttribute(attribute, translated);
    });
  });

  document.title = currentLanguage() === "ky"
    ? "Линия Роста - интернет-дүкөн"
    : "Линия Роста - интернет-магазин";
  const description = document.querySelector('meta[name="description"]');
  if (description) {
    description.content = currentLanguage() === "ky"
      ? "Линия Роста интернет-дүкөнү: керме шыптар, SPC ламинат, комплекттер жана шыпты онлайн эсептөө."
      : "Интернет-магазин Линия Роста: натяжные потолки, SPC ламинат, комплектующие, визуализация и онлайн-просчет потолка.";
  }
}

async function init() {
  elements.whatsappHeader.href = whatsAppLink(currentLanguage() === "ky"
    ? "Саламатсызбы! Линия Роста сайты боюнча маалымат алгым келет."
    : "Здравствуйте! Пишу с сайта Линия Роста.");
  applyTheme(state.theme);
  bindGlobalEvents();
  renderRoute();
  if (await loadProducts()) renderRoute();
}

function bindGlobalEvents() {
  document.addEventListener("click", (event) => {
    const link = event.target.closest("a[data-link]");
    if (!link) return;
    const url = new URL(link.href);
    if (url.origin !== window.location.origin) return;
    event.preventDefault();
    navigate(url.pathname + url.search + url.hash);
  });

  window.addEventListener("popstate", renderRoute);
  window.addEventListener("scroll", updateHeader, { passive: true });
  updateHeader();
}

async function loadProducts() {
  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), 12000);
  try {
    const response = await fetch("/api/products", { signal: controller.signal });
    if (!response.ok) throw new Error(`Catalog request failed: ${response.status}`);
    const data = await response.json();
    state.products = Array.isArray(data.products) ? data.products : [];
    pruneCart();
    return true;
  } catch {
    toast("Каталог временно не загрузился. Проверьте сервер.");
    return false;
  } finally {
    window.clearTimeout(timeout);
  }
}

function renderRoute() {
  const pathname = normalizePath(window.location.pathname);
  const route = routes.has(pathname) ? pathname : "/";
  document.body.dataset.route = route.slice(1) || "home";
  updateCartCount();
  updateActiveNav(route);

  if (route === "/") renderHome();
  if (route === "/catalog") renderCatalog();
  if (route === "/cart") renderCartPage();
  if (route === "/checkout") renderCheckout();
  if (route === "/success") renderSuccess();
  if (route === "/measure") renderMeasure();
  if (route === "/installer") renderInstaller();
  if (route === "/privacy") renderPrivacyPolicy();
  if (route === "/terms") renderTerms();
  if (route === "/data-consent") renderDataConsent();

  appendLegalFooter();
  applyLanguageToPage();

  requestAnimationFrame(() => {
    observeReveal();
    updateHeader();
    const targetId = decodeURIComponent(window.location.hash.slice(1));
    const target = targetId ? document.getElementById(targetId) : null;
    if (target) {
      target.scrollIntoView({ behavior: "smooth", block: "start" });
    } else {
      window.scrollTo(0, 0);
    }
  });
}

